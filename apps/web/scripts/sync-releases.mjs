import { existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const REPO = "NachikethReddyY/ay2627s2-cicdp-nachiketh";
const OUT = fileURLToPath(new URL("../src/pages/changelog-releases.generated.ts", import.meta.url));

const headers = { Accept: "application/vnd.github+json", "User-Agent": "learnslop-changelog" };
if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

const toEntry = (release) => {
  const lines = (release.body ?? "").split("\n").map((line) => line.trim()).filter(Boolean);
  return {
    date: release.published_at ?? release.created_at,
    tag: release.tag_name,
    title: release.name || release.tag_name,
    url: release.html_url,
    summary: lines.find((line) => !/^([-*#]|\d+\.)/.test(line)) ?? "",
    changes: lines.filter((line) => /^[-*] /.test(line)).map((line) => line.replace(/^[-*] /, "")),
  };
};

const render = (items) =>
  `// Generated by apps/web/scripts/sync-releases.mjs from the GitHub releases of ${REPO}. Do not edit by hand.\n` +
  `export type ReleaseEntry = { date: string; tag: string; title: string; url: string; summary: string; changes: string[] };\n\n` +
  `export const releases: ReleaseEntry[] = ${JSON.stringify(items, null, 2)};\n`;

try {
  const res = await fetch(`https://api.github.com/repos/${REPO}/releases?per_page=50`, { headers });
  if (!res.ok) throw new Error(`GitHub responded ${res.status}`);
  const releases = (await res.json()).filter((release) => !release.draft).map(toEntry);
  writeFileSync(OUT, render(releases));
  console.log(`changelog: wrote ${releases.length} release(s)`);
} catch (err) {
  if (existsSync(OUT)) {
    console.warn(`changelog: keeping the last generated releases (${err.message})`);
  } else {
    console.warn(`changelog: no releases fetched and no generated file yet (${err.message}); writing an empty list`);
    writeFileSync(OUT, render([]));
  }
}

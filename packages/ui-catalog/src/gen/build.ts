import { z } from "zod";
import { ID_RE, MAX_BLOCKS, MAX_SPEC_BYTES, MIN_BLOCKS } from "../core/caps.ts";
import { blockSchema, envelopeSchema } from "../core/envelope.ts";
import type { BlockModule } from "../core/parse.ts";
import { RESERVED } from "../core/reserved.ts";

const byType = (mods: readonly BlockModule[]) => [...mods].sort((a, b) => (a.type < b.type ? -1 : a.type > b.type ? 1 : 0));

// "input" so props with defaults stay optional: the schema checks what the model sends, before parsing.
const toJson = (schema: z.ZodType) => z.toJSONSchema(schema, { io: "input" });

/**
 * The whole spec as one zod schema: the envelope with `blocks` narrowed to the registered types.
 * With no modules, `blocks` items are z.never(), so the schema accepts no spec at all.
 * Not covered here (parseSpec only): check(), budgets, duplicate ids, the byte cap, and per-block leniency.
 */
export const specSchema = (mods: readonly BlockModule[]) => {
  const blocks = byType(mods).map((m) => blockSchema(m.type, m.schema));
  const item = blocks.length ? z.discriminatedUnion("type", blocks as [(typeof blocks)[number], ...typeof blocks]) : z.never();
  return envelopeSchema.extend({ blocks: z.array(item).min(MIN_BLOCKS).max(MAX_BLOCKS) });
};

export const jsonSchema = (mods: readonly BlockModule[]): string => {
  const { $schema, ...rest } = toJson(specSchema(mods));
  return JSON.stringify({ $schema, title: "LearnQuest visual spec", ...rest }, null, 2) + "\n";
};

/** The block catalog the model reads: envelope rules, then one section per block type, sorted. */
export const catalog = (mods: readonly BlockModule[]): string => {
  const head = [
    "# LearnQuest visual blocks",
    "",
    "<!-- Generated by `pnpm --filter @learnquest/ui-catalog gen`. Do not edit. -->",
    "",
    "A visual is one JSON object: `{\"v\": 1, \"blocks\": [...]}`.",
    "",
    `- \`blocks\` holds ${MIN_BLOCKS} to ${MAX_BLOCKS} blocks, each \`{"type", "id", "props"}\` with no other keys.`,
    `- \`id\` is unique in the spec and matches \`${ID_RE.source}\`.`,
    "- `props` takes only the keys listed for its type. Every visual block needs `alt` text.",
    `- The whole spec is at most ${MAX_SPEC_BYTES} bytes.`,
    `- These types are reserved and never available: ${RESERVED.map((t) => `\`${t}\``).join(", ")}.`,
    "",
    "## Blocks",
    "",
  ];
  if (!mods.length) return [...head, "No block types are available yet.", ""].join("\n");
  const sections = byType(mods).flatMap((m) => [
    `### ${m.type}`,
    "",
    `At most ${m.budget} per spec.`,
    "",
    m.prompt.trim(),
    "",
    "Props schema:",
    "",
    "```json",
    JSON.stringify(toJson(m.schema), (k, v) => (k === "$schema" ? undefined : v)),
    "```",
    "",
  ]);
  return [...head, ...sections].join("\n");
};
